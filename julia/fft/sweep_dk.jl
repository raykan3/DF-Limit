include(joinpath(@__DIR__, "fft_cond.jl"))
xs = [-3.5, -2.0, -1.0, 0.0, 1.0, 2.5, 4.0]
function report(label, c; kw...)
    T = build(c; kw...)
    e = [cdf_fft(T, x; npan = 10, n = 64) - DFExact.cdf(x, 1; c = c) for x in xs]
    @printf("%-34s check %.1e  max|err| %.2e  (x: %s)\n", label, check_table(T), maximum(abs, e), join([@sprintf("%.0e", abs(v)) for v in e], " "))
end
build(0.0; N = 2^12, na = 8)
report("c=0 default (2^16, dw .25, na 96)", 0.0)
report("c=0 N=2^15 (vmax 12.6)", 0.0; N = 2^15)
report("c=0 dw=0.5 (N=2^15, vmax 25)", 0.0; N = 2^15, dw = 0.5)
report("c=0 dw=1.0 (N=2^14, vmax 25)", 0.0; N = 2^14, dw = 1.0)
report("c=0 na=48", 0.0; na = 48)
report("c=0 na=160", 0.0; na = 160)
report("c=0 sigma=0.3", 0.0; sigma = 0.3)
report("c=0 sigma=-0.2", 0.0; sigma = -0.2)
report("c=-5 default", -5.0)
report("c=-5 dw=1.0 (N=2^14)", -5.0; N = 2^14, dw = 1.0)
report("c=2 default", 2.0)
report("c=-20 default", -20.0)
