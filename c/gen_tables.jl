# Writes c/tables.c: the constant tables of the C engine, generated from the Julia engine (the reference) and from
# the series file of Raymond's MATLAB programs:
#   GT, GE          tanh(th)/th and sech th as series in th^2 (the Girsanov forms)
#   G2SER, G3SER    g(z) of the stationary start, Taylor coefficients in z
#   D1SER, D2SER    D(z)/e^c of models 2, 3 as coefficients of z^j lam^i c^k (from dfx_series.m)
#   K0A             the asymptotic series of e^z K_0(z)
#   K0C, K0F        the Taylor cells of e^z K_0(z) (side 1/4 on [0,25)^2, side 1/8 on [0,2)^2), seeded by AMOS here
# Run from the repository root: julia --project=julia c/gen_tables.jl
using Printf
include(joinpath(@__DIR__, "..", "julia", "DFExact.jl")); using .DFExact; const D = DFExact
out = open(joinpath(@__DIR__, "tables.c"), "w")
println(out, "/* generated by c/gen_tables.jl from the Julia engine: do not edit */")
println(out, "#include \"dflimit.h\"")
function writevec(name, v)
    @printf(out, "const double %s[%d] = {", name, length(v))
    for (k, x) in enumerate(v); @printf(out, "%s%.17g", k == 1 ? "" : ",", x); k % 6 == 0 && print(out, "\n"); end
    println(out, "};")
end
writevec("GT", D.GT); writevec("GE", D.GE)
writevec("G2SER", D.G2SER); writevec("G3SER", D.G3SER)
writevec("K0A", D.K0A)
# the determinant series from dfx_series.m: S.D1(j,i,k) = value
src = read(joinpath(@__DIR__, "..", "..", "DF-Limit", "public", "dfx_series.m"), String)
for (name, cname) in (("D1", "D1SER"), ("D2", "D2SER"))
    m = match(Regex("S\\.$name = zeros\\((\\d+),(\\d+),(\\d+)\\);"), src)
    nj, ni, nk = parse.(Int, m.captures)
    T = zeros(nj, ni, nk)
    for mm in eachmatch(Regex("S\\.$name\\((\\d+),(\\d+),(\\d+)\\) = ([-0-9.Ee+]+);"), src)
        j, i, k = parse.(Int, mm.captures[1:3]); T[j, i, k] = parse(Float64, mm.captures[4])
    end
    @printf(out, "const int %s_NJ = %d, %s_NI = %d, %s_NK = %d;\n", cname, nj, cname, ni, cname, nk)
    @printf(out, "const double %s[%d] = {   /* [j][i][k], k fastest */", cname, nj * ni * nk)
    n = 0
    for j in 1:nj, i in 1:ni, k in 1:nk
        n += 1; @printf(out, "%s%.17g", n == 1 ? "" : ",", T[j, i, k]); n % 6 == 0 && print(out, "\n")
    end
    println(out, "};")
end
# the K_0 cells: K0C[n, cell] with cell = i + 1 + K0NI j, n = 0..K0N; stored as interleaved re, im
D.k0tables!()
function writecells(name, C)
    nn, nc = size(C)
    @printf(out, "const int %s_N = %d, %s_CELLS = %d;\n", name, nn, name, nc)
    @printf(out, "const double %s[%d] = {   /* [cell][n][re, im] */", name, 2 * nn * nc)
    n = 0
    for c in 1:nc, k in 1:nn
        z = C[k, c]
        n += 1; @printf(out, "%s%.17g,%.17g", n == 1 ? "" : ",", real(z), imag(z)); n % 3 == 0 && print(out, "\n")
    end
    println(out, "};")
end
writecells("K0C", D.K0C); writecells("K0F", D.K0F)
close(out)
println("tables.c written: ", filesize(joinpath(@__DIR__, "tables.c")), " bytes")
