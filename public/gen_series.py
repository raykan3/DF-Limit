# Taylor coefficients in z = mu^2 of the Fredholm determinants of Nabeya and Tanaka (1990),
# Theorem 4, D_j(lambda; c, x) e^{c}, with lambda*x = (z + c^2)/2 (x eliminated);
# output: MATLAB table A{j}(k+1, m+1, q+1) = coefficient of z^k lambda^m c^q
# usage: python3 gen_series.py [output file, default nt_series.m]  (requires sympy)
# TR_CFLIM uses the series for |z| < 4 and the closed form otherwise;
# TRATIO_TEST checks that the two agree on |z| = 4.
import sympy as sp, sys
lam, z, c = sp.symbols('lam z c')
K = 30; P = K + 8
S = sum((-z)**k/sp.factorial(2*k+1) for k in range(P))     # sin(mu)/mu
C = sum((-z)**k/sp.factorial(2*k) for k in range(P))       # cos(mu)
x = (z + c**2)/(2*lam)
mu2 = z
E = {}
E[1] = C + (c+lam)*S
E[2] = (lam**2 + 2*lam*x - c**2*lam - c**3)/mu2*S - c**2*C/mu2 + (2*lam**2 - 4*c*lam*x - 2*c**2*lam)*(C-1)/mu2**2
E[4] = ((c**5 + (c**4 - 4*(c**2+3*c+27)*lam - 8*x*(c**2-3*c-3))*lam)/mu2**2*S
        - 24*(c**4 - 8*x*lam**2 + 4*(c+1)*(x**2-3)*lam)*lam/mu2**3*(S + C/mu2 - 1/mu2)
        + (c**4/mu2**2 + 8*(c**3*(c+2*x) - 4*(c**2+3*c+6)*lam)*lam/mu2**3)*C
        + 4*(c**4 - 4*(c**2+3*c-3)*lam + 2*c**2*x*(c+3))*lam/mu2**3)
out = []
for j in (1,2,4):
    e = sp.expand(sp.together(E[j]) * 1)
    num, den = sp.fraction(sp.together(E[j]))
    num = sp.expand(num); den = sp.factor(den)
    # den should be a monomial in z (times constants)
    dpoly = sp.Poly(den, z); assert len(dpoly.terms()) == 1, den
    (dz,), dc = dpoly.terms()[0]
    npoly = sp.Poly(num, z)
    coeffs = {}
    for (pz,), co in npoly.terms():
        k = pz - dz
        if k < 0:
            assert sp.simplify(co) == 0, (j, pz, co)
            continue
        if k <= K:
            coeffs[k] = sp.expand(co/dc)
    # tabulate in lam^m c^q
    rows = []
    for k in range(K+1):
        co = coeffs.get(k, 0)
        pl = sp.Poly(co, lam, c) if co != 0 else None
        if pl is not None:
            for (m,q), v in pl.terms():
                rows.append((k,m,q,v))
    out.append((j,rows))
    print('j',j,'den z^%d'%dz, 'terms',len(rows), file=sys.stderr)
with open((sys.argv[1] if len(sys.argv) > 1 else 'nt_series.m'),'w') as f:
    f.write('function A = nt_series(j)\n%NT_SERIES  Taylor coefficients of the Nabeya-Tanaka determinants (generated by gen_series.py):\n%   A(k+1,m+1,q+1) = coefficient of z^k lambda^m c^q in e^c D_j, z = mu^2 = 2 lambda x - c^2.\n')
    for j,rows in out:
        M = max(r[1] for r in rows); Q = max(r[2] for r in rows)
        f.write('if j == %d\n    A = zeros(%d,%d,%d);\n' % (j, K+1, M+1, Q+1))
        for k,m,q,v in rows:
            f.write('    A(%d,%d,%d) = %s;\n' % (k+1, m+1, q+1, sp.N(v, 20)))
        f.write('    return\nend\n')
    f.write("error('nt_series: j must be 1, 2 or 4');\nend\n")
print('done')
